#!/usr/bin/env python3
"""Read-only inventory of non-main remote branches for issue #513.

For every remote branch except the base branch this tool records the branch
HEAD, committer date, merge-base, whether the branch content is already fully
present in the base branch (squash-merge aware), linked pull requests and a
classification with a recommended action. Output is a deterministic TSV or
JSON snapshot suitable for review and diffing in CI.

This tool is intentionally non-destructive: it never deletes, prunes, pushes or
rewrites refs. Ref removal is a separate owner-approved change; the existing
helpers live in ``tools/prune_branch_refs.py`` and
``tools/atomic_ref_cleanup.py``. ``--fetch`` only updates local remote-tracking
refs for the named remote; it never deletes branches on the server.

Classification (first match wins):

- ``open_pr`` / ``draft_pr`` -- an open pull request still uses the branch;
- ``merged`` -- HEAD is an ancestor of the base branch, or a merged PR into
  the base branch has the same head SHA;
- ``content_in_main`` -- every file changed in ``merge-base..HEAD`` is
  byte-identical in the base branch, so a squash/rebase merge landed the same
  content at a different SHA;
- ``closed_unmerged`` -- only closed, non-merged pull requests are linked;
- ``no_pr`` -- the GitHub API reports no pull request for the branch;
- ``unknown`` -- GitHub metadata is unavailable (offline, no ``gh``, rate
  limit) and the git evidence is inconclusive, or a merged pull request
  targeted the base branch but the branch has newer commits whose content is
  not in the base branch (post-merge drift needs human review).

Recommended action:

- ``merged`` / ``content_in_main`` -> ``delete_safe`` (content only; owner
  approval is still required before any ref is actually removed);
- ``open_pr`` / ``draft_pr`` -> ``keep``;
- ``closed_unmerged`` / ``no_pr`` / ``unknown`` -> ``needs_owner_review``.

Usage::

    python3 tools/branch_inventory_audit.py
    python3 tools/branch_inventory_audit.py --fetch --output tools/branch-inventory-audit.tsv
    python3 tools/branch_inventory_audit.py --format json --no-github
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from collections.abc import Iterable, Sequence
from dataclasses import asdict, dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REPO = "askarahodov/Harbor-Transfer-Portal"
DEFAULT_REMOTE = "origin"
DEFAULT_BASE = "main"

CATEGORIES = (
    "merged",
    "content_in_main",
    "open_pr",
    "draft_pr",
    "closed_unmerged",
    "no_pr",
    "unknown",
)

_ACTION_BY_CATEGORY = {
    "merged": "delete_safe",
    "content_in_main": "delete_safe",
    "open_pr": "keep",
    "draft_pr": "keep",
    "closed_unmerged": "needs_owner_review",
    "no_pr": "needs_owner_review",
    "unknown": "needs_owner_review",
}

_RISK_BY_CATEGORY = {
    "merged": "low",
    "content_in_main": "low",
    "open_pr": "high",
    "draft_pr": "high",
    "closed_unmerged": "medium",
    "no_pr": "medium",
    "unknown": "high",
}

TSV_COLUMNS = (
    "branch",
    "head_sha",
    "committed_at",
    "merge_base",
    "files_changed",
    "content_in_main",
    "ancestor_of_main",
    "merged_into_main",
    "pull_requests",
    "category",
    "risk",
    "action",
)

TSV_PREAMBLE = (
    "# Harbor Transfer Portal branch inventory audit (issue #513) - read-only.",
    "# Generated by `python3 tools/branch_inventory_audit.py`; do not edit by hand.",
)


class AuditError(RuntimeError):
    """Raised when repository state cannot be read safely."""


@dataclass(frozen=True, slots=True)
class PullRequest:
    number: int
    state: str
    draft: bool
    base: str
    merged: bool
    head_ref: str
    head_sha: str


@dataclass(frozen=True, slots=True)
class BranchFacts:
    name: str
    head_sha: str
    committed_at: str
    merge_base: str | None
    ancestor_of_main: bool
    content_in_main: bool | None
    files_changed: int


@dataclass(frozen=True, slots=True)
class AuditRow:
    branch: str
    head_sha: str
    committed_at: str
    merge_base: str
    files_changed: int
    content_in_main: str
    ancestor_of_main: str
    merged_into_main: str
    pull_requests: str
    category: str
    risk: str
    action: str


def _run_git(args: Sequence[str], *, check: bool = True) -> subprocess.CompletedProcess[str]:
    env = dict(os.environ)
    env["GIT_LITERAL_PATHSPECS"] = "1"
    proc = subprocess.run(
        ["git", "--no-pager", *args],
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        env=env,
        check=False,
    )
    if check and proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()
        raise AuditError(f"git {' '.join(args)} failed: {detail}")
    return proc


def _resolve_commit(ref: str) -> str | None:
    proc = _run_git(["rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"], check=False)
    value = proc.stdout.strip()
    return value if proc.returncode == 0 and value else None


def list_remote_branches(remote: str, base: str) -> list[tuple[str, str]]:
    """Return ``(branch, head_sha)`` for every remote branch except ``base``."""
    prefix = f"refs/remotes/{remote}/"
    proc = _run_git(
        ["for-each-ref", "--format=%(refname)%09%(objectname)", f"refs/remotes/{remote}"]
    )
    branches: dict[str, str] = {}
    for line in proc.stdout.splitlines():
        if not line.strip():
            continue
        refname, _, sha = line.partition("\t")
        if not refname.startswith(prefix) or not sha:
            continue
        name = refname[len(prefix) :]
        if name in {"HEAD", base}:
            continue
        branches[name] = sha
    return sorted(branches.items())


def collect_branch_facts(name: str, head_sha: str, base_sha: str) -> BranchFacts:
    committed_at = _run_git(["show", "-s", "--format=%cI", head_sha]).stdout.strip()

    merge_base_proc = _run_git(["merge-base", base_sha, head_sha], check=False)
    merge_base = merge_base_proc.stdout.strip() if merge_base_proc.returncode == 0 else None
    if not merge_base:
        merge_base = None

    ancestor = _run_git(
        ["merge-base", "--is-ancestor", head_sha, base_sha], check=False
    ).returncode == 0

    files: list[str] = []
    content_in_main: bool | None = None
    if merge_base is not None:
        diff = _run_git(
            ["diff", "--name-only", "--no-renames", "-z", merge_base, head_sha]
        )
        files = [item for item in diff.stdout.split("\0") if item]
        if not files:
            content_in_main = True
        else:
            quiet = _run_git(
                ["diff", "--quiet", "--no-renames", base_sha, head_sha, "--", *files],
                check=False,
            )
            if quiet.returncode == 0:
                content_in_main = True
            elif quiet.returncode == 1:
                content_in_main = False
            else:
                content_in_main = None

    return BranchFacts(
        name=name,
        head_sha=head_sha,
        committed_at=committed_at,
        merge_base=merge_base,
        ancestor_of_main=ancestor,
        content_in_main=content_in_main,
        files_changed=len(files),
    )


def load_pull_requests(repo: str) -> tuple[PullRequest, ...] | None:
    """Load every pull request once; return ``None`` when GitHub is unavailable."""
    endpoint = f"repos/{repo}/pulls?state=all&per_page=100"
    try:
        proc = subprocess.run(
            ["gh", "api", "--paginate", "--slurp", endpoint],
            text=True,
            capture_output=True,
            check=False,
        )
    except (FileNotFoundError, OSError):
        return None
    if proc.returncode != 0:
        return None
    try:
        pages = json.loads(proc.stdout or "[]")
    except json.JSONDecodeError:
        return None
    if not isinstance(pages, list):
        return None

    wanted_repo = repo.casefold()
    requests: list[PullRequest] = []
    for page in pages:
        if not isinstance(page, list):
            return None
        for item in page:
            if not isinstance(item, dict):
                continue
            head = item.get("head") or {}
            head_repo = (head.get("repo") or {}).get("full_name")
            if not isinstance(head_repo, str) or head_repo.casefold() != wanted_repo:
                continue
            base = item.get("base") or {}
            number = item.get("number")
            if not isinstance(number, int):
                continue
            requests.append(
                PullRequest(
                    number=number,
                    state=str(item.get("state") or ""),
                    draft=bool(item.get("draft")),
                    base=str(base.get("ref") or ""),
                    merged=item.get("merged_at") is not None,
                    head_ref=str(head.get("ref") or ""),
                    head_sha=str(head.get("sha") or ""),
                )
            )
    requests.sort(key=lambda pr: pr.number)
    return tuple(requests)


def pull_requests_for_branch(
    pull_requests: Iterable[PullRequest], branch: str
) -> list[PullRequest]:
    return [pr for pr in pull_requests if pr.head_ref == branch]


def _is_merged_into_base(pr: PullRequest, base: str, head_sha: str) -> bool:
    return pr.merged and pr.base == base and pr.head_sha == head_sha


def classify(
    facts: BranchFacts,
    pull_requests: Sequence[PullRequest],
    *,
    github_available: bool,
    base: str = DEFAULT_BASE,
) -> str:
    """Return the first matching category for a branch (see module docstring)."""
    if any(pr.state == "open" and not pr.draft for pr in pull_requests):
        return "open_pr"
    if any(pr.state == "open" and pr.draft for pr in pull_requests):
        return "draft_pr"
    if facts.ancestor_of_main:
        return "merged"
    if any(
        _is_merged_into_base(pr, base, facts.head_sha) for pr in pull_requests
    ):
        return "merged"
    if facts.content_in_main:
        return "content_in_main"
    if any(pr.merged and pr.base == base for pr in pull_requests):
        # A merged PR targeted the base branch but its head no longer matches:
        # the branch advanced after merge and the extra content is not in base.
        return "unknown"
    if pull_requests:
        return "closed_unmerged"
    return "no_pr" if github_available else "unknown"


def format_pull_requests(pull_requests: Sequence[PullRequest]) -> str:
    if not pull_requests:
        return "-"
    parts: list[str] = []
    for pr in sorted(pull_requests, key=lambda item: item.number):
        flags = [pr.state or "unknown"]
        if pr.draft:
            flags.append("draft")
        if pr.merged:
            flags.append("merged")
        if pr.base:
            flags.append(f"base={pr.base}")
        parts.append(f"#{pr.number}({','.join(flags)})")
    return " ".join(parts)


def _merged_flag(facts: BranchFacts, category: str) -> str:
    if facts.ancestor_of_main or facts.content_in_main or category == "merged":
        return "true"
    return "false"


def _tri_state(value: bool | None) -> str:
    if value is None:
        return "unknown"
    return "true" if value else "false"


def build_row(
    facts: BranchFacts,
    pull_requests: Sequence[PullRequest],
    *,
    github_available: bool,
    base: str = DEFAULT_BASE,
) -> AuditRow:
    category = classify(
        facts, pull_requests, github_available=github_available, base=base
    )
    return AuditRow(
        branch=facts.name,
        head_sha=facts.head_sha,
        committed_at=facts.committed_at,
        merge_base=facts.merge_base or "none",
        files_changed=facts.files_changed,
        content_in_main=_tri_state(facts.content_in_main),
        ancestor_of_main="true" if facts.ancestor_of_main else "false",
        merged_into_main=_merged_flag(facts, category),
        pull_requests=format_pull_requests(pull_requests),
        category=category,
        risk=_RISK_BY_CATEGORY[category],
        action=_ACTION_BY_CATEGORY[category],
    )


def summarize(rows: Sequence[AuditRow]) -> dict[str, dict[str, int]]:
    categories = {name: 0 for name in CATEGORIES}
    actions = {name: 0 for name in sorted(set(_ACTION_BY_CATEGORY.values()))}
    for row in rows:
        categories[row.category] += 1
        actions[row.action] += 1
    return {"categories": categories, "actions": actions}


def render_tsv(
    rows: Sequence[AuditRow], *, base_sha: str | None = None
) -> str:
    ordered = sorted(rows, key=lambda row: row.branch)
    summary = summarize(ordered)
    categories = " ".join(f"{name}={summary['categories'][name]}" for name in CATEGORIES)
    actions = " ".join(f"{name}={summary['actions'][name]}" for name in sorted(summary["actions"]))
    lines: list[str] = list(TSV_PREAMBLE)
    if base_sha:
        lines.append(f"# Base: {base_sha}")
    lines.append(f"# Categories: {categories}")
    lines.append(f"# Actions: {actions}")
    lines.append("\t".join(TSV_COLUMNS))
    for row in ordered:
        lines.append("\t".join(str(getattr(row, column)) for column in TSV_COLUMNS))
    return "\n".join(lines) + "\n"


def render_json(
    rows: Sequence[AuditRow], *, base: str, base_sha: str | None = None
) -> str:
    ordered = sorted(rows, key=lambda row: row.branch)
    payload = {
        "schema_version": 1,
        "tool": "tools/branch_inventory_audit.py",
        "mode": "read-only",
        "base": base,
        "base_sha": base_sha,
        "branches": [asdict(row) for row in ordered],
        "summary": summarize(ordered),
    }
    return json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Read-only inventory and classification of remote branches (issue #513). "
            "Never deletes refs; deletion is a separate owner-approved change."
        ),
        epilog=(
            "Exit status is 0 for a successful report. Use --output to write the "
            "snapshot to a file; stdout is used otherwise. Without GitHub access "
            "PR-linked categories degrade to 'unknown' unless git evidence is conclusive."
        ),
    )
    parser.add_argument(
        "--repo",
        default=DEFAULT_REPO,
        help=f"GitHub repository in owner/name form (default: {DEFAULT_REPO})",
    )
    parser.add_argument(
        "--remote",
        default=DEFAULT_REMOTE,
        help=f"git remote name to read (default: {DEFAULT_REMOTE})",
    )
    parser.add_argument(
        "--base",
        default=DEFAULT_BASE,
        help=f"base branch excluded from the inventory (default: {DEFAULT_BASE})",
    )
    parser.add_argument(
        "--format",
        choices=("tsv", "json"),
        default="tsv",
        help="output format (default: tsv)",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="write the report to this path instead of stdout",
    )
    parser.add_argument(
        "--fetch",
        action="store_true",
        help=(
            "run 'git fetch --prune <remote>' first; this updates local "
            "remote-tracking refs only and never deletes server branches"
        ),
    )
    parser.add_argument(
        "--no-github",
        action="store_true",
        help="skip the GitHub API and classify from git evidence only",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    options = _build_parser().parse_args(argv)

    if options.fetch:
        _run_git(["fetch", "--prune", options.remote])

    base_sha = _resolve_commit(f"refs/remotes/{options.remote}/{options.base}")
    if base_sha is None:
        raise AuditError(
            f"cannot resolve refs/remotes/{options.remote}/{options.base}; "
            "run with --fetch or check the remote/base names"
        )

    github_available = not options.no_github
    pull_requests: tuple[PullRequest, ...] = ()
    if github_available:
        loaded = load_pull_requests(options.repo)
        if loaded is None:
            github_available = False
            print(
                "warning: GitHub API unavailable; PR-linked categories fall back to git evidence",
                file=sys.stderr,
            )
        else:
            pull_requests = loaded

    rows: list[AuditRow] = []
    for name, head_sha in list_remote_branches(options.remote, options.base):
        facts = collect_branch_facts(name, head_sha, base_sha)
        linked = pull_requests_for_branch(pull_requests, name)
        rows.append(
            build_row(
                facts,
                linked,
                github_available=github_available,
                base=options.base,
            )
        )

    text = (
        render_json(rows, base=options.base, base_sha=base_sha)
        if options.format == "json"
        else render_tsv(rows, base_sha=base_sha)
    )

    if options.output:
        Path(options.output).parent.mkdir(parents=True, exist_ok=True)
        Path(options.output).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except AuditError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc